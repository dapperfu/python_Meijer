class ConstructorSearchAnalyzer:
    """
    Specialized analyzer for Constructor.io search endpoints.

    Analyzes how Meijer uses Constructor.io for search functionality
    and extracts item structures to build comprehensive MeijerItem classes.
    """

    def __init__(self, log_file_path: str):
        self.log_file_path = Path(log_file_path)
        self.flows = []
        self.analysis = ConstructorAnalysis()

        # Setup logging
        logging.basicConfig(level=logging.INFO)
        self.logger = logging.getLogger(__name__)

        # Constructor.io endpoint patterns
        self.constructor_endpoints = {
            "search": "/search/",
            "autocomplete": "/autocomplete/",
            "browse": "/browse/",
            "behavior": "/behavior",
            "behavioral_action": "/behavioral_action/",
            "v2/behavioral_action": "/v2/behavioral_action/",
        }

    def load_flows(self) -> bool:
        """Load flows from the mitmproxy log file."""
        try:
            if not self.log_file_path.exists():
                self.logger.error(f"Log file not found: {self.log_file_path}")
                return False

            self.logger.info(f"Loading flows from: {self.log_file_path}")

            with open(self.log_file_path, "rb") as f:
                reader = FlowReader(f)

                flow_count = 0
                for flow_obj in reader.stream():
                    self.flows.append(flow_obj)
                    flow_count += 1

                    if flow_count % 1000 == 0:
                        self.logger.info(f"Loaded {flow_count} flows...")

                self.logger.info(f"Successfully loaded {len(self.flows)} flows")
                return True

        except Exception as e:
            self.logger.error(f"Error loading flows: {e}")
            return False

    def analyze_constructor_flows(self) -> None:
        """Analyze flows specifically for Constructor.io endpoints."""
        self.logger.info("Starting Constructor.io flow analysis...")

        constructor_flow_count = 0

        for i, flow_obj in enumerate(self.flows):
            try:
                if not isinstance(flow_obj, http.HTTPFlow):
                    continue

                request = flow_obj.request
                response = flow_obj.response

                if not hasattr(request, "pretty_url") or not request.pretty_url:
                    continue

                url_str = request.pretty_url

                # Check if this is a Constructor.io endpoint
                if "cnstrc.com" in url_str:
                    constructor_flow_count += 1
                    endpoint_type = self._get_constructor_endpoint_type(url_str)
                    self._analyze_constructor_flow(flow_obj, endpoint_type)

                if (i + 1) % 1000 == 0:
                    self.logger.info(f"Analyzed {i + 1}/{len(self.flows)} flows...")

            except Exception as e:
                self.logger.error(f"Error analyzing flow {i}: {e}")

        self.logger.info(f"Found {constructor_flow_count} Constructor.io flows")
        self._analyze_patterns()

    def _get_constructor_endpoint_type(self, url_str: str) -> Optional[str]:
        """Determine the Constructor.io endpoint type."""
        for endpoint_path, endpoint_type in self.constructor_endpoints.items():
            if endpoint_path in url_str:
                return endpoint_type.replace("/", "")
        return "unknown"

    def _analyze_constructor_flow(
        self, flow_obj: http.HTTPFlow, endpoint_type: str
    ) -> None:
        """Analyze a single Constructor.io flow."""
        request = flow_obj.request
        response = flow_obj.response

        # Parse URL components
        parsed_url = urlparse(request.pretty_url)
        query_params = parse_qs(parsed_url.query)

        # Extract common parameters
        api_key = query_params.get("key", [None])[0]
        client_id = query_params.get("i", [None])[0]
        session_id = query_params.get("s", [None])[0]

        if api_key and not self.analysis.api_key:
            self.analysis.api_key = api_key
        if client_id and not self.analysis.client_id:
            self.analysis.client_id = client_id
        if session_id and not self.analysis.session_id:
            self.analysis.session_id = session_id

        flow_data = {
            "url": request.pretty_url,
            "method": request.method,
            "status_code": response.status_code if response else None,
            "timestamp": getattr(flow_obj, "timestamp_start", None),
            "path": parsed_url.path,
            "query_params": query_params,
            "request_headers": dict(request.headers)
            if hasattr(request, "headers")
            else {},
            "response_headers": dict(response.headers)
            if response and hasattr(response, "headers")
            else {},
            "request_body": self._extract_and_parse_body(request),
            "response_body": self._extract_and_parse_body(response)
            if response
            else None,
        }

        # Store flow data by endpoint type
        if endpoint_type == "search":
            self.analysis.search_calls.append(flow_data)
            # Extract search term
            search_term = self._extract_search_term(flow_data)
            if search_term:
                self.analysis.search_terms[search_term] += 1

        elif endpoint_type == "autocomplete":
            self.analysis.autocomplete_calls.append(flow_data)
            # Extract search term from autocomplete
            search_term = self._extract_search_term(flow_data)
            if search_term:
                self.analysis.search_terms[search_term] += 1

        elif endpoint_type == "browse":
            self.analysis.browse_calls.append(flow_data)

        elif endpoint_type in ["behavior", "behavioral_action", "v2/behavioral_action"]:
            self.analysis.behavior_calls.append(flow_data)

        # Track API parameters
        for param, values in query_params.items():
            if values:
                self.analysis.api_parameters[param][values[0]] += 1

        # Extract item structures from response
        if response and flow_data["response_body"]:
            self._extract_item_structures(flow_data["response_body"], endpoint_type)

    def _extract_search_term(self, flow_data: Dict[str, Any]) -> Optional[str]:
        """Extract search term from flow data."""
        # From URL path
        path = flow_data.get("path", "")
        if "/search/" in path:
            # Path like /search/milk
            term = path.split("/search/")[-1].split("?")[0]
            if term and term != "search":
                return term
        elif "/autocomplete/" in path:
            # Path like /autocomplete/milk
            term = path.split("/autocomplete/")[-1].split("?")[0]
            if term and term != "autocomplete":
                return term

        # From query parameters
        query_params = flow_data.get("query_params", {})
        if "term" in query_params:
            term = query_params["term"][0] if query_params["term"] else None
            if term:
                return term

        return None

    def _extract_and_parse_body(self, http_obj) -> Union[Dict, List, str, None]:
        """Extract and parse HTTP body content."""
        try:
            if hasattr(http_obj, "content") and http_obj.content:
                try:
                    text_content = http_obj.content.decode("utf-8")
                    try:
                        return json.loads(text_content)
                    except json.JSONDecodeError:
                        return text_content
                except UnicodeDecodeError:
                    hex_content = http_obj.content.hex()
                    return (
                        hex_content[:200] + "..."
                        if len(hex_content) > 200
                        else hex_content
                    )
        except Exception:
            pass
        return None

    def _extract_item_structures(
        self, response_data: Union[Dict, List, str], endpoint_type: str
    ) -> None:
        """Extract and analyze item structures from Constructor.io responses."""
        if not isinstance(response_data, dict):
            return

        # Look for results/items in different response structures
        items = []

        # Common Constructor.io response structures
        if "results" in response_data:
            items = response_data["results"]
        elif "response" in response_data and isinstance(
            response_data["response"], dict
        ):
            resp = response_data["response"]
            if "results" in resp:
                items = resp["results"]
            elif "products" in resp:
                items = resp["products"]
        elif "sections" in response_data:
            # Autocomplete responses have sections
            for section in response_data["sections"]:
                if "options" in section:
                    items.extend(section["options"])

        # Analyze each item
        for item in items:
            if isinstance(item, dict):
                self._analyze_single_item(item, endpoint_type)
                self.analysis.item_structures.append(item)

    def _analyze_single_item(self, item: Dict[str, Any], endpoint_type: str) -> None:
        """Analyze a single item structure to understand fields and types."""

        # Flatten nested structures for field analysis
        def flatten_dict(d, parent_key="", sep="_"):
            """Flatten nested dictionary."""
            items = []
            for k, v in d.items():
                new_key = f"{parent_key}{sep}{k}" if parent_key else k
                if isinstance(v, dict):
                    items.extend(flatten_dict(v, new_key, sep=sep).items())
                elif isinstance(v, list) and v and isinstance(v[0], dict):
                    # For lists of dicts, analyze the first item
                    items.extend(flatten_dict(v[0], f"{new_key}_item", sep=sep).items())
                else:
                    items.append((new_key, v))
            return dict(items)

        flattened = flatten_dict(item)

        # Analyze all fields
        for field_name, field_value in flattened.items():
            # Count field frequency
            self.analysis.unique_item_fields[field_name] += 1

            # Determine and store data type
            field_type = type(field_value).__name__
            if field_name not in self.analysis.field_data_types:
                self.analysis.field_data_types[field_name] = field_type
            elif self.analysis.field_data_types[field_name] != field_type:
                # Handle mixed types
                existing_type = self.analysis.field_data_types[field_name]
                if not existing_type.startswith("Union"):
                    self.analysis.field_data_types[field_name] = (
                        f"Union[{existing_type}, {field_type}]"
                    )

    def _analyze_patterns(self) -> None:
        """Analyze patterns in Constructor.io API usage."""
        # Extract common filters
        all_search_calls = self.analysis.search_calls + self.analysis.browse_calls

        filters = defaultdict(Counter)
        for call in all_search_calls:
            query_params = call.get("query_params", {})
            for param, values in query_params.items():
                if param.startswith("filters[") and values:
                    filter_name = param.replace("filters[", "").replace("]", "")
                    filters[filter_name][values[0]] += 1

        self.analysis.common_filters = dict(filters)

