    def _convert_to_python_type(self, type_str: str) -> str:
        """Convert discovered types to proper Python types."""
        type_map = {
            "str": "str",
            "int": "int",
            "float": "float",
            "bool": "bool",
            "list": "List[Any]",
            "dict": "Dict[str, Any]",
            "NoneType": "None",
        }

        if type_str.startswith("Union["):
            return type_str

        return type_map.get(type_str, "Any")

    def _to_snake_case(self, camel_str: str) -> str:
        """Convert camelCase or other formats to snake_case."""
        import re

        # Handle data_field patterns
        if camel_str.startswith("data_"):
            return camel_str.lower()

        # Convert camelCase
        s1 = re.sub("(.)([A-Z][a-z]+)", r"\1_\2", camel_str)
        s2 = re.sub("([a-z0-9])([A-Z])", r"\1_\2", s1)
        return s2.lower().replace("-", "_").replace(" ", "_")

